#!/usr/bin/env node
/**
 * Phase 2: turn the raw Figma exports into web-ready assets.
 *
 *   node scripts/optimize-images.mjs          # process changed files only
 *   node scripts/optimize-images.mjs --force  # rebuild everything
 *
 * Input : _incoming/figma-images/** (originals, git-ignored)
 *         _incoming/figma-svg/**    (SVG exports, git-ignored)
 *         scripts/image-map.json    (original file -> readable name)
 * Output: public/images/<name>.webp
 *         public/svg/<name>.svg
 *         src/content/images.ts     (generated index with sizes for next/image)
 *
 * Rules: width = min(original, 2x the largest size Figma shows it at, 2560 px).
 *        WebP quality 80 (alpha kept). next/image serves AVIF/WebP per browser at runtime.
 */
import { createRequire } from "node:module";
import { cp, mkdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const sharp = require("sharp");

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const force = process.argv.includes("--force");
const MAX_WIDTH = 2560;

const map = JSON.parse(await readFile(path.join(root, "scripts/image-map.json"), "utf8"));
const index = {};
let written = 0;
let skipped = 0;
let bytesIn = 0;
let bytesOut = 0;

for (const entry of map) {
  if (!entry.name) continue; // designer placeholder, intentionally left out

  const src = path.join(root, entry.source);
  const out = path.join(root, "public/images", `${entry.name}.webp`);
  if (!existsSync(src)) {
    console.error(`missing source: ${entry.source}`);
    process.exitCode = 1;
    continue;
  }

  const meta = await sharp(src, { limitInputPixels: false }).metadata();
  const target = Math.min(meta.width, Math.max(2 * entry.displayMaxPx[0], 64), MAX_WIDTH);
  bytesIn += (await stat(src)).size;

  const fresh =
    !force && existsSync(out) && (await stat(out)).mtimeMs >= (await stat(src)).mtimeMs;
  if (fresh) {
    skipped++;
  } else {
    await mkdir(path.dirname(out), { recursive: true });
    // Logos sit in fixed boxes in Figma with their transparent padding cropped
    // ("stretch" fill), so trim that padding here.
    const isLogo = /^shared\/(retailers|footer-partners)\//.test(entry.name);
    const pipeline = sharp(src, { limitInputPixels: false }).rotate();
    if (isLogo) pipeline.trim({ threshold: 10 });
    await (isLogo ? sharp(await pipeline.toBuffer()) : pipeline)
      .resize({ width: target, withoutEnlargement: true })
      .webp({ quality: 80, alphaQuality: 90, effort: 5 })
      .toFile(out);
    written++;
  }

  const outMeta = await sharp(out).metadata();
  bytesOut += (await stat(out)).size;
  index[entry.name] = {
    src: `/images/${entry.name}.webp`,
    width: outMeta.width,
    height: outMeta.height,
  };
}

// SVGs: copied, then files over 40 KB are minified with svgo (Phase 10: the patterns and
// generated illustrations were 120-640 KB). floatPrecision 5 keeps the render pixel-identical
// apart from anti-aliasing (checked by rendering before/after in Chrome). A result is kept
// only when it is smaller.
const svgIn = path.join(root, "_incoming/figma-svg");
const svgOut = path.join(root, "public/svg");
if (existsSync(svgIn)) {
  if (force) await rm(svgOut, { recursive: true, force: true });
  await cp(svgIn, svgOut, { recursive: true });
  const { optimize } = await import("svgo");
  const { readdir } = await import("node:fs/promises");
  let saved = 0;
  for (const entry of await readdir(svgOut, { recursive: true, withFileTypes: true })) {
    if (!entry.isFile() || !entry.name.endsWith(".svg")) continue;
    const file = path.join(entry.parentPath, entry.name);
    if ((await stat(file)).size < 40 * 1024) continue;
    const input = await readFile(file, "utf8");
    const { data } = optimize(input, { path: file, floatPrecision: 5, plugins: ["preset-default"] });
    if (data.length < input.length) {
      saved += input.length - data.length;
      await writeFile(file, data);
    }
  }
  console.log(`svgo: saved ${Math.round(saved / 1024)} KB`);
}

const keys = Object.keys(index).sort();
const body = keys
  .map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(index[k])},`)
  .join("\n");
await writeFile(
  path.join(root, "src/content/images.ts"),
  `// GENERATED by scripts/optimize-images.mjs. Do not edit by hand.
// Use with next/image:  <Image {...img("home/hero-sunorange")} alt="..." />

export const images = {
${body}
} as const;

export type ImageKey = keyof typeof images;

/** Returns src, width and height for next/image. */
export const img = (key: ImageKey) => images[key];
`,
);

const mb = (b) => (b / 1e6).toFixed(1);
console.log(
  `images: ${keys.length} (${written} written, ${skipped} unchanged) · ${mb(bytesIn)} MB -> ${mb(bytesOut)} MB`,
);
